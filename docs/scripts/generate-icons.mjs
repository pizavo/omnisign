// @ts-check
/**
 * Generate theme-aware React-component copies of the desktop app's SVG drawables for the docs.
 *
 * The app stores monochrome icons with hard-coded `black` fills/strokes and recolors them at
 * render time via Compose's `tint`. This script copies every drawable, rewrites those `black`
 * values to `currentColor` so CSS can theme them, and emits a typed barrel (`index.ts`) mapping
 * a short name to its SVGR component. Run automatically before `start`/`build`/`typecheck`
 * (see package.json), so the docs icon set stays in sync with the app — there is a single source
 * of truth (`composeApp/.../drawable`) and no committed copies to drift.
 */
import {readFileSync, writeFileSync, readdirSync, rmSync, mkdirSync} from 'node:fs';
import {join, dirname, basename} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE_DIR = join(here, '..', '..', 'composeApp', 'src', 'commonMain', 'composeResources', 'drawable');
const OUT_DIR = join(here, '..', 'src', 'icons');

/** Replace the app's hard-coded black fills/strokes with `currentColor` so CSS can theme them. */
function themeable(svg) {
  return svg.replace(/(fill|stroke)="(?:black|#000000|#000)"/gi, '$1="currentColor"');
}

/** `icon_eu_crossed` -> `IconEuCrossed`. */
function toPascalCase(stem) {
  return stem
    .split(/[_-]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

const files = readdirSync(SOURCE_DIR)
  .filter((file) => file.endsWith('.svg'))
  .sort();

if (files.length === 0) {
  throw new Error(`No SVG icons found in ${SOURCE_DIR}`);
}

rmSync(OUT_DIR, {recursive: true, force: true});
mkdirSync(OUT_DIR, {recursive: true});

const entries = files.map((file) => {
  const stem = basename(file, '.svg');
  writeFileSync(join(OUT_DIR, file), themeable(readFileSync(join(SOURCE_DIR, file), 'utf8')));
  return {file, name: stem.replace(/^icon_/, ''), component: toPascalCase(stem)};
});

const header =
  '// AUTO-GENERATED by scripts/generate-icons.mjs — do not edit.\n' +
  '// Source: composeApp/src/commonMain/composeResources/drawable/*.svg\n' +
  '// Regenerated on every `npm start` / `npm run build` / `npm run typecheck`.\n\n';

const indexTs =
  header +
  "import type {ComponentType, SVGProps} from 'react';\n" +
  entries.map((e) => `import ${e.component} from './${e.file}';`).join('\n') +
  '\n\n' +
  'export type IconName =\n' +
  entries.map((e) => `  | '${e.name}'`).join('\n') +
  ';\n\n' +
  'export const icons: Record<IconName, ComponentType<SVGProps<SVGSVGElement> & {title?: string}>> = {\n' +
  entries.map((e) => `  '${e.name}': ${e.component},`).join('\n') +
  '\n};\n';

writeFileSync(join(OUT_DIR, 'index.ts'), indexTs);

console.log(`Generated ${entries.length} themeable icons in ${OUT_DIR}`);
